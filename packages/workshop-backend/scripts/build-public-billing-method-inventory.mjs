import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript6";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..");
const PACKAGES = join(ROOT, "packages");
const OUTPUT = join(HERE, "..", "src", "generated", "public-billing-methods.ts");

function unwrap(expression) {
  while (ts.isAsExpression(expression) || ts.isSatisfiesExpression(expression)) {
    expression = expression.expression;
  }
  return expression;
}

function literalMethodKeys(path) {
  const source = ts.createSourceFile(
    path,
    readFileSync(path, "utf8"),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const result = new Set();
  const visit = (node) => {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) &&
        node.name.text.endsWith("_BILLING_METHODS") && node.initializer !== undefined) {
      const initializer = unwrap(node.initializer);
      if (!ts.isObjectLiteralExpression(initializer)) {
        throw new TypeError(`${path}: ${node.name.text} must be an object literal.`);
      }
      for (const property of initializer.properties) {
        if (ts.isSpreadAssignment(property)) continue;
        if (!ts.isPropertyAssignment(property)) {
          throw new TypeError(`${path}: ${node.name.text} has a non-property entry.`);
        }
        const value = unwrap(property.initializer);
        if (ts.isCallExpression(value) && value.arguments.length === 1 &&
            ts.isStringLiteral(value.arguments[0])) {
          result.add(value.arguments[0].text);
          continue;
        }
        if (ts.isObjectLiteralExpression(value)) {
          const methodKey = value.properties.find(entry =>
            ts.isPropertyAssignment(entry) && entry.name.getText(source) === "methodKey");
          if (methodKey && ts.isPropertyAssignment(methodKey) &&
              ts.isStringLiteral(methodKey.initializer)) {
            result.add(methodKey.initializer.text);
          }
        }
        // Composite registries can reference entries already declared in another local registry.
        // The literal declaration is collected when that registry is visited.
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return result;
}

const inventory = [];
for (const directory of readdirSync(PACKAGES, { withFileTypes: true })) {
  if (!directory.isDirectory() || !directory.name.startsWith("gatekeeper-")) continue;
  const path = join(PACKAGES, directory.name, "src", "billing-methods.ts");
  try {
    for (const billingMethodKey of literalMethodKeys(path)) {
      inventory.push({
        vendorId: directory.name.slice("gatekeeper-".length).replaceAll("-", "_"),
        billingMethodKey,
      });
    }
  } catch (error) {
    if (error?.code === "ENOENT") continue;
    throw error;
  }
}
inventory.sort((left, right) =>
  left.vendorId.localeCompare(right.vendorId) ||
  left.billingMethodKey.localeCompare(right.billingMethodKey));

const content = `// Generated by scripts/build-public-billing-method-inventory.mjs.\n` +
  `// Do not edit manually.\n\n` +
  `/** Build-time inventory of stable caller-visible Gatekeeper billing method keys. */\n` +
  `export const publicBillingMethodInventory = ${JSON.stringify(inventory, null, 2)} as const;\n`;

let previous;
try {
  previous = readFileSync(OUTPUT, "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}
if (previous !== content) {
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, content);
  console.log(`Generated ${inventory.length} public Gatekeeper billing methods.`);
} else {
  console.log(`Public Gatekeeper billing methods up-to-date (${inventory.length}).`);
}
